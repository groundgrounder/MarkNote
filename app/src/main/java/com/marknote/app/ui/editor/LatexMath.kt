package com.marknote.app.ui.editor

/**
 * LaTeX 公式的分隔符规则。
 *
 * 单独一个文件、且**不引用任何 Android 类型**：这几个正则是纯逻辑，
 * tools/checks 里的 JVM 断言（CheckLatexMath）直接拿它们跑，
 * 不用起模拟器就能验证边界判定 —— 边界写得对不对是这件事里最容易出错的部分。
 */

/**
 * 单 `$…$` 行内公式，按 Pandoc 的边界规则：
 * - 开 `$` 后不能紧跟空白（`$ \alpha$` 不是公式）
 * - 闭 `$` 前不能是空白（`$\alpha $` 不是公式）
 * - 闭 `$` 后不能紧跟数字（挡住「$10 和 $20 之间」这类金额）
 * - 内容不跨行（行内公式跨段落没有意义）
 *
 * 最后一条 `(?![\d$])` 除了挡数字，还**挡住闭 `$` 紧邻另一个 `$`** 的情况：
 * 「价格 $5，$$E=mc^2$$」里的 `$5，` 会跨到后面那个 `$$` 上，被误判成内容为 `5，` 的公式，
 * 顺带把真正的 `$$…$$` 拆坏。Pandoc 没这条，但「金额 + 紧挨着的公式」在中文写作里很常见。
 *
 * 这条会顺带牺牲一种畸形写法：两个单美元公式紧贴的 `$x$$y$` 里，前者不再被识别
 * （闭 `$` 与第二个公式的开 `$` 相撞）。这个位置与「金额紧挨公式」**完全同构**，
 * 纯前瞻无法区分；若要两者兼顾就得往后扫找 `$$`，在长段落里是 O(n²) 的回溯。
 * 取常见场景、舍畸形输入。
 *
 * 三条规则**全部写进正则**、靠 `matchAt` 整体成功或失败，而不是「先匹配再检查」——
 * 因为处理器返回 null 时要靠框架回滚 index，中途推进过就会错位。
 *
 * `[^\s$]` 的双重作用：既挡空白，也保证 `$$` 不会被当成「内容为空的单美元公式」抢走。
 *
 * 转义（`\$`）天然安全：反斜杠由 BackslashInlineProcessor 更早吃掉，轮不到这里。
 */
internal val inlineMathPattern = Regex("""\$([^\s$](?:[^\n$]*[^\s$])?)\$(?![\d$])""")

/** `$$…$$`：段落内的行内公式，与 ext-latex 自带的写法保持一致（`[\\s\\S]+?` 最短匹配） */
internal val doubleDollarMathPattern = Regex("""\$\$([\s\S]+?)\$\$""")

/**
 * 一次扫出两种写法，供大纲跳转做「源码 → 渲染文本」换算用（见 EditorScreen.plainTitle）。
 * 渲染后分隔符会被剥掉、只留公式源，所以估算标题文字时必须做同样的事。
 *
 * group 1 = `$$` 的公式源，group 2 = 单 `$` 的公式源。
 * `$$` 那个分支写在前面：正则的 alternation 从左往右优先，`$$x$$` 不会被单 `$` 抢走。
 */
internal val mathSegmentPattern = Regex(
    doubleDollarMathPattern.pattern + "|" + inlineMathPattern.pattern,
)
